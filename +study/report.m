function report(study)
%REPORT Compact navigable result index; the CSV/MAT tables retain full precision.
fid=fopen(fullfile(study.outputDir,'index.html'),'w','n','UTF-8');
if fid<0, error('tbench:Write','Cannot write the run index.'); end
cleanup=onCleanup(@()fclose(fid)); %#ok<NASGU>
fprintf(fid,['<!doctype html><html lang="en"><meta charset="utf-8"><title>Tremor benchmark</title>' ...
    '<style>body{font:16px system-ui;max-width:1200px;margin:3em auto;padding:0 1em;color:#182b3a}' ...
    'table{border-collapse:collapse;width:100%%}td,th{border-bottom:1px solid #ccd7df;padding:.65em;text-align:left}' ...
    'th{background:#eff4f7}code{font-size:.9em}a{color:#135aac}.note{background:#eff4f7;padding:1em}</style>']);
fprintf(fid,'<h1>Essential tremor benchmark</h1><p><code>%s</code></p><p>Status: <strong>%s</strong></p>',escape(study.runId),escape(study.status));
fprintf(fid,'<p>%d participants: %d ET, %d controls. Primary feature level: %s. Selection priority: %s.</p>', ...
    study.manifestAudit.subjects,study.manifestAudit.ET,study.manifestAudit.controls, ...
    escape(study.config.clinical.featureLevel),escape(study.config.clinical.priority));
fprintf(fid,['<p class="note">These are outer-fold research estimates. Control rhythms and subject-level ET-like false positives are separate endpoints. ' ...
    'The nominal control target is an empirical training operating point, not a population-specificity guarantee. ' ...
    'All-training deployment fits are saved separately and do not validate themselves.</p>']);
fprintf(fid,'<h2>Primary clinical comparison</h2><table><tr><th>Pipeline</th><th>Control FP</th><th>Lower severity captured</th><th>Higher severity captured</th><th>ET Spearman</th><th>Balanced log loss</th><th>Coverage</th></tr>');
Q=study.clinicalScorecard(strcmp({study.clinicalScorecard.level},study.config.clinical.featureLevel));
for k=1:numel(Q)
    r=Q(k);
    fprintf(fid,'<tr><td>%s</td><td>%d / %d</td><td>%d / %d</td><td>%d / %d</td><td>%s</td><td>%s</td><td>%.1f%%</td></tr>', ...
        escape(r.pipelineId),r.controlFalsePositives,r.controls,r.mildCaptured,r.mildSubjects,r.severeCaptured,r.severeSubjects, ...
        number(r.severitySpearman),number(r.balancedLogLoss),100*r.clinicalCoverage);
end
fprintf(fid,'</table><p>Lower/higher severity means training-relative tertiles unless provided clinical categories or fixed score cuts were supplied.</p>');
if study.config.motion.enabled
    fprintf(fid,['<h2>Independent motion benchmark</h2><p class="note">Motion is an evaluation target. EMG detectors receive no motion or clinical labels. ' ...
        'A reference-negative interval requires a declared calibrated amplitude limit. Indeterminate intervals are reported separately. ' ...
        'The person-calibrated waveform readout and the unseen-person RMS readout answer different questions.</p>']);
    fprintf(fid,'<table><tr><th>Pipeline</th><th>Stratum</th><th>People</th><th>RMS gain over tonic/MVC baseline</th><th>Input coverage</th></tr>');
    Q=study.motion.summary;
    for k=1:numel(Q)
        r=Q(k); if ~strcmp(r.level,'F1'), continue; end
        fprintf(fid,'<tr><td>%s</td><td>%s</td><td>%d</td><td>%s</td><td>%s</td></tr>', ...
            escape(r.pipelineId),escape(r.subgroup),r.subjects,number(r.gain),number(r.inputCoverage));
    end
    fprintf(fid,['</table><p>Gains are dimensionless decoder utilities; negative gains remain visible. ' ...
        'They do not quantify all information in an EMG recording or establish which muscle caused the motion. ' ...
        'Read the reference coverage beside lower-severity results.</p><ul>']);
    motionLinks={'motion_referenceAudit.csv','Motion import, units, clock and negative-limit audit'; ...
        'motion_coverage.csv','All reference trials and unavailable intervals'; ...
        'motion_agreement.csv','M1-M3 and M6 trial outcomes with three reference witnesses'; ...
        'motion_agreementSummary.csv','Subject-first outcomes by severity and task type'; ...
        'motion_waveformPrediction.csv','M4 person-calibrated waveform and compression errors'; ...
        'motion_waveformSummary.csv','Waveform evaluability and retained utility'; ...
        'motion_predictions.csv','M4 unseen-subject RMS prediction and physical error'; ...
        'motion_retention.csv','Frozen and retrained motion utility retention'; ...
        'motion_contrasts.csv','Paired subject uncertainty'; ...
        'motion_residualRepeatability.csv','Repeatability conditional on observed motion'; ...
        'motion_clinicalScorecard.csv','Motion-only clinical comparator'; ...
        'motion_calibration.csv','Synthetic motion challenge; not device calibration'};
    for k=1:size(motionLinks,1), fprintf(fid,'<li><a href="%s">%s</a></li>',motionLinks{k,1},motionLinks{k,2}); end
    if study.config.motion.coherence.enabled, fprintf(fid,'<li><a href="motion_coherence.csv">M5 coherence and conditional contribution audit</a></li>'); end
    fprintf(fid,'</ul>');
end
links={'selected_parameters.csv','Selected and all-training parameter sets'; ...
    'installation.csv','Native interface and clean-tone installation probes'; ...
    'parameter_spaces.csv','Declared method-specific parameters and choices'; ...
    'optimizationTrace.csv','Training-only refinement rounds and termination'; ...
    'parameter_stability.csv','Outer-fold parameter-choice stability'; ...
    'tuning_scores.csv','Eligibility, mild/severe capture and weak/late signal recovery'; ...
    'clinicalPredictions.csv','Every outer prediction, score, decision and status'; ...
    'clinicalScorecard.csv','Clinical panel over all supported feature levels'; ...
    'pairedContrasts.csv','Paired participant comparisons'; ...
    'rhythmSummary.csv','B1 raw rhythm yields and physical burden'; ...
    'calibrationTest.csv','B4 independent known-signal challenges'; ...
    'B5_controlInjection_summary.csv','B4 optional held-out control counterfactuals'; ...
    'transferAudit.csv','G0 transfer and pure-FM carrier audit'; ...
    'B6_ICC.csv','B6 ICC, absolute SEM and MDC'; ...
    'clinicalRetention.csv','B7 frozen and retrained clinical utility changes'; ...
    'physiologyRetention.csv','B7 physiological utility changes'; ...
    'phenotypeScorecard.csv','B8 phenotype subsets'; ...
    'qualitySummary.csv','B8 failures and broad-frequency witnesses'; ...
    'candidate_catalog.csv','Complete tested parameter catalog'; ...
    'method_availability.csv','Implemented and unavailable method entries'; ...
    'run_manifest.json','Configuration and reproducibility record'};
fprintf(fid,'<h2>Detailed results</h2><ul>');
for k=1:size(links,1), fprintf(fid,'<li><a href="%s">%s</a></li>',links{k,1},links{k,2}); end
fprintf(fid,'</ul><p>Empty or unsupported endpoints are labelled explicitly. Original recordings are referenced by source hashes; no patient signal truth is inferred from diagnosis or TETRAS.</p></html>');
end
function value=number(x)
value='NA'; if isfinite(x), value=sprintf('%.3f',x); end
end
function value=escape(value)
value=strrep(char(value),'&','&amp;'); value=strrep(value,'<','&lt;');
value=strrep(value,'>','&gt;'); value=strrep(value,'"','&quot;');
end
